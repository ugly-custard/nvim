  config = function(_, dashboard)
    -- Own group so italics survive colorscheme reloads without touching AlphaFooter itself.
    local function italic_footer()
      local hl = vim.api.nvim_get_hl(0, { name = "AlphaFooter", link = false })
      vim.api.nvim_set_hl(0, "AlphaFooterItalic", { fg = hl.fg, bg = hl.bg, italic = true })
    end
    italic_footer()
    vim.api.nvim_create_autocmd("ColorScheme", { callback = italic_footer })

